#!/usr/bin/env node
/**
 * Universal game onboarding CLI.
 *
 *   node scripts/onboard-game.mjs --html5 <dir> [--id forest --title 森林神庙 --manifest-out <file>]
 *   node scripts/onboard-game.mjs --swf <file> [--manifest-out <file>]
 *   node scripts/onboard-game.mjs --registry --games config/games --research config/research-games
 *
 * Probes are read-only. A manifest is only written when --manifest-out is
 * supplied; generated manifests are never written into config automatically.
 */
import path from 'node:path';
import {writeFile} from 'node:fs/promises';
import {parseArgs} from 'node:util';
import {probeGame} from '../server/game-probe.mjs';
import {DEFAULT_ADAPTER, loadGameRegistry, validateGameManifest} from '../server/game-adapter.mjs';

const {values} = parseArgs({
  options: {
    html5: {type: 'string'},
    swf: {type: 'string'},
    registry: {type: 'boolean', default: false},
    games: {type: 'string'},
    research: {type: 'string'},
    id: {type: 'string'},
    title: {type: 'string'},
    subtitle: {type: 'string'},
    'storage-prefix': {type: 'string'},
    'manifest-out': {type: 'string'},
  },
});

function print(value) {
  process.stdout.write(JSON.stringify(value, null, 2) + '\n');
}

function decodeTitle(value) {
  return String(value ?? '')
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'").trim();
}

function generatedHtml5Manifest(report, values) {
  const base = (report.templeId || report.dir).replace(/[^a-z0-9-]/gi, '-').toLowerCase();
  const id = values.id ?? (/^[a-z]/.test(base) ? base : 'g-' + base);
  const title = values.title ?? (decodeTitle(report.title) || id);
  return {
    schemaVersion: 1,
    id,
    title,
    subtitle: values.subtitle ?? '',
    runtime: 'html5-phaser',
    adapter: DEFAULT_ADAPTER,
    order: 100,
    online: true,
    capabilities: {
      authority: true, spectator: true, levelVote: true,
      restartVote: true, returnVote: true, save: true,
    },
    package: {
      dir: report.dir,
      entry: report.entry,
      levels: report.levelsPath,
      templeId: report.templeId,
      storagePrefix: values['storage-prefix'] ?? ('fb-' + id),
    },
    evidence: [],
    notes: 'Generated by scripts/onboard-game.mjs after a read-only package probe.',
  };
}

try {
  if (values.registry) {
    const gamesDir = values.games ?? path.join('config', 'games');
    const researchDir = values.research ?? path.join('config', 'research-games');
    print(await loadGameRegistry({gamesDir, researchDir}));
  } else if (values.swf) {
    const report = await probeGame({kind: 'swf', file: values.swf});
    print(report);
    if (report.verdict === 'REJECTED') process.exitCode = 2;
  } else if (values.html5) {
    const report = await probeGame({kind: 'html5', dir: values.html5});
    print(report);
    if (!report.onlineEligible) {
      process.exitCode = 2;
    } else if (values['manifest-out']) {
      const manifest = validateGameManifest(generatedHtml5Manifest(report, values),
        {file: 'generated'});
      await writeFile(values['manifest-out'], JSON.stringify(manifest, null, 2) + '\n', 'utf8');
      process.stderr.write('WROTE ' + values['manifest-out'] + '\n');
    }
  } else {
    process.stderr.write('usage: --html5 <dir> | --swf <file> | --registry\n');
    process.exitCode = 2;
  }
} catch (error) {
  process.stderr.write('ONBOARD_FAILED: ' + (error?.message ?? String(error)) + '\n');
  process.exitCode = 1;
}
